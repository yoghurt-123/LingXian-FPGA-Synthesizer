// 兼容原接口的单音 DDS：32 位相位累加器 + 共享正弦表。
// Adapted from Sipeed TangMega-138KPro-example/audio/audio_sinewave.
module rom_save_sin #(
    parameter [31:0] PHASE_STEP = 32'd39163557,
    parameter VOLUME_SHIFT = 3
)(input clk, input rst_n, input sample_tick, output signed [15:0] data);
    reg [31:0] phase;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) phase <= 0;
        else if (sample_tick) phase <= phase + PHASE_STEP;
    wire signed [15:0] sine_value;
    sine_lut u_lut(.clk(clk), .addr(phase[31:24]), .data(sine_value));
    assign data = sine_value >>> VOLUME_SHIFT;
endmodule
